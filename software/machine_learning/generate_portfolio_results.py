from pathlib import Path
import json
import joblib
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[2]
ML = ROOT / "software" / "machine_learning"
OUT = ROOT / "media" / "results"
OUT.mkdir(parents=True, exist_ok=True)

df = pd.read_csv(ROOT / "data" / "synthetic_glucose_demo.csv")
bundle = joblib.load(ML / "outputs" / "glucose_rf.joblib")
model = bundle["model"]
features = bundle["features"]

X = df[features]
y = df["glucose_mg_dl"].to_numpy()
pred = model.predict(X)

# Full-data diagnostics only, NOT independent test results
plt.figure(figsize=(7, 6))
plt.scatter(y, pred, alpha=0.5, color="#456B55")
plt.plot([50,250], [50,250], "--", color="#193D32")
plt.xlabel("Synthetic reference (mg/dL)")
plt.ylabel("Prediction (mg/dL)")
plt.title("Synthetic data: fitted-model diagnostic")
plt.tight_layout()
plt.savefig(OUT / "prediction_scatter.png", dpi=180)
plt.close()

plt.figure(figsize=(7, 5))
plt.scatter(pred, y-pred, alpha=0.5, color="#87A994")
plt.axhline(0, linestyle="--", color="#193D32")
plt.xlabel("Prediction (mg/dL)")
plt.ylabel("Residual (mg/dL)")
plt.title("Synthetic data: residual diagnostic")
plt.tight_layout()
plt.savefig(OUT / "residual_plot.png", dpi=180)
plt.close()

plt.figure(figsize=(8, 5))
order = np.argsort(model.feature_importances_)
plt.barh(
    np.array(features)[order],
    model.feature_importances_[order],
    color="#456B55"
)
plt.xlabel("Random Forest importance")
plt.title("Synthetic data: feature importance")
plt.tight_layout()
plt.savefig(OUT / "feature_importance.png", dpi=180)
plt.close()

# Copy independent train/test metrics generated by train_model.py
metrics_path = ML / "outputs" / "metrics.json"
metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
(ROOT / "docs" / "synthetic_metrics.json").write_text(
    json.dumps(metrics, indent=2), encoding="utf-8"
)

print("Generated plots and synthetic metrics.")
print(json.dumps(metrics, indent=2))
